export function getIconByName(iconName) {
  if (!iconName || typeof iconName !== 'string') return null;
  const resolved = HABIT_ICON_LEGACY_ALIASES[iconName] || iconName;
  return iconMap[resolved] || null;
}

export function getHabitIconLabel(iconName) {
  return HABIT_ICON_LABELS[iconName] || iconName;
}

function toPickerOption(name) {
  return { name, label: getHabitIconLabel(name) };
}

/** Grupos temáticos para el picker (incluye bucket "Otros" con iconos no listados). */
export function getHabitIconGroups() {
  const assigned = new Set();

  const groups = HABIT_ICON_GROUP_DEFS.map(({ id, label, icons }) => {
    const items = icons
      .filter((name) => iconMap[name] && !HABIT_ICON_PICKER_EXCLUDED.has(name))
      .map((name) => {
        assigned.add(name);
        return toPickerOption(name);
      });
    return { id, label, icons: items };
  }).filter((group) => group.icons.length > 0);

  const unassigned = Object.keys(iconMap)
    .filter((name) => !HABIT_ICON_PICKER_EXCLUDED.has(name) && !assigned.has(name))
    .map(toPickerOption)
    .sort((a, b) => a.label.localeCompare(b.label, 'es'));

  if (unassigned.length > 0) {
    const miscGroup = groups.find((group) => group.id === 'misc');
    if (miscGroup) {
      miscGroup.icons.push(...unassigned);
      miscGroup.icons.sort((a, b) => a.label.localeCompare(b.label, 'es'));
    } else {
      groups.push({ id: 'misc', label: 'Otros', icons: unassigned });
    }
  }

  return groups;
}

/** Lista plana para compatibilidad (ordenada por grupo temático). */
export function getHabitIconOptions() {
  return getHabitIconGroups().flatMap((group) => group.icons);
}

